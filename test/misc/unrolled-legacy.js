const SHA1_END = '// END generated SHA-1 compression';
const MD5_START = '// BEGIN generated MD5 compression';
const MD5_END = '// END generated MD5 compression';
const RIPEMD160_START = '// BEGIN generated RIPEMD-160 one-shot compression';
const RIPEMD160_END = '// END generated RIPEMD-160 one-shot compression';


/** Generates the SHA-256 two-round ring used by SHA2_32B.process() and sha256Compress(). */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const C_START = '// BEGIN generated SHA-256 compression';
const C_END = '// END generated SHA-256 compression';
const P_START = '// BEGIN generated SHA-256 class rounds';
const P_END = '// END generated SHA-256 class rounds';

// FIPS 180-4 section 4.2.2: first 32 bits of the fractional parts of the cube roots of the first
// 64 primes. Computed here with an integer cube root, independently of the table in src/sha2.ts.
function sha256K() {
  const primes = [];
  for (let n = 2; primes.length < 64; n++) if (primes.every((p) => n % p)) primes.push(n);
  const cbrt = (n) => {
    let lo = 0n,
      hi = 1n << 64n;
    while (lo < hi) {
      const mid = (lo + hi + 1n) >> 1n;
      if (mid * mid * mid <= n) lo = mid;
      else hi = mid - 1n;
    }
    return lo;
  };
  return primes.map((p) => Number(cbrt(BigInt(p) << 96n) & 0xffffffffn));
}

// One SHA-256 round over a 16-word rolling schedule W. `k` is the round index expression and `j`
// the schedule slot variable it declares.
function round(W, k, j, ind) {
  return [
    `const ${j} = ${k === 'i' ? 'i' : `(${k})`} & 15;`,
    `if (i >= 16) {`,
    `  const W15 = ${W}[(${j} + 1) & 15], W2 = ${W}[(${j} + 14) & 15];`,
    `  ${W}[${j}] = ((rotr(W2, 17) ^ rotr(W2, 19) ^ (W2 >>> 10)) + ${W}[(${j} + 9) & 15] + (rotr(W15, 7) ^ rotr(W15, 18) ^ (W15 >>> 3)) + ${W}[${j}]) | 0;`,
    `}`,
    `T1 = (H + (rotr(E, 6) ^ rotr(E, 11) ^ rotr(E, 25)) + (G ^ (E & (F ^ G))) + SHA256_K[${k}] + ${W}[${j}]) | 0;`,
    `T2 = ((rotr(A, 2) ^ rotr(A, 13) ^ rotr(A, 22)) + ((A & B) ^ (C & (A ^ B)))) | 0;`,
    `H = G; G = F; F = E; E = (D + T1) | 0; D = C; C = B; B = A; A = (T1 + T2) | 0;`,
  ].map((l) => ind + l);
}

// A 16-word ring avoids materializing the full 64-word schedule. Two straight rounds per iteration
// keep loop overhead low without the register-pressure cliffs of wider unrolling.
function ring(W, ind) {
  return [
    `${ind}for (let i = 0; i < 64; i += 2) {`,
    ...round(W, 'i', 'j', ind + '  '),
    ...round(W, 'i + 1', 'j1', ind + '  '),
    `${ind}}`,
  ].join('\n');
}

export function generateCompress() {
  return `${C_START}
// Generated by test/misc/unrolled-sha2.js from FIPS 180-4. Do not edit by hand.
// prettier-ignore
function sha256Compress(S: TArg<Int32Array>, W: TArg<Uint32Array>): void {
  let A = S[0], B = S[1], C = S[2], D = S[3], E = S[4], F = S[5], G = S[6], H = S[7];
  let T1 = 0, T2 = 0;
${ring('W', '  ')}
  S[0] = (A + S[0]) | 0; S[1] = (B + S[1]) | 0; S[2] = (C + S[2]) | 0; S[3] = (D + S[3]) | 0;
  S[4] = (E + S[4]) | 0; S[5] = (F + S[5]) | 0; S[6] = (G + S[6]) | 0; S[7] = (H + S[7]) | 0;
}
${C_END}`;
}

export function generateProcess() {
  return `${P_START}
    // Generated by test/misc/unrolled-sha2.js from FIPS 180-4. Do not edit by hand.
    // A 16-word ring avoids materializing the full 64-word schedule. Two straight rounds keep
    // loop overhead low without the register-pressure cliffs of wider unrolling.
    // prettier-ignore
${ring('SHA256_W', '    ')}
    ${P_END}`;
}

function checkRegion(source, startMarker, endMarker, generated) {
  const start = source.indexOf(startMarker);
  const end = source.indexOf(endMarker, start);
  assert.notEqual(start, -1, `missing source marker: ${startMarker}`);
  assert.notEqual(end, -1, `missing source marker: ${endMarker}`);
  assert.equal(source.slice(start, end + endMarker.length), generated);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const c = generateCompress(),
    p = generateProcess();
  if (process.argv[2] === '--check') {
    const source = readFileSync(new URL('../../src/sha2.ts', import.meta.url), 'utf8');
    checkRegion(source, C_START, C_END, c);
    checkRegion(source, P_START, P_END, p);
    // Both rings index SHA256_K at runtime, so check the emitted table too.
    const table = source.match(
      /const SHA256_K = \/\* @__PURE__ \*\/ Uint32Array\.from\(\[([^\]]*)\]\);/
    );
    assert.ok(table, 'missing SHA256_K table');
    assert.deepEqual(
      table[1].match(/0x[0-9a-f]+/gi).map((x) => Number(x)),
      sha256K()
    );
    console.log('src/sha2.ts SHA-256 rounds and SHA256_K match generator');
  } else if (process.argv.length === 2) console.log(c + '\n\n' + p);
  else {
    console.error('Usage: node test/misc/unrolled-sha2.js [--check]');
    process.exitCode = 1;
  }
}

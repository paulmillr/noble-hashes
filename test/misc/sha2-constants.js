import { readFileSync } from 'node:fs';

const MASK32 = 0xffffffffn;

function integerRoot(n, degree) {
  let bits = 0;
  for (let x = n; x; x >>= 1n) bits++;
  let low = 0n;
  let high = 1n << BigInt(Math.ceil(bits / degree) + 1);
  while (low + 1n < high) {
    const mid = (low + high) >> 1n;
    if (mid ** BigInt(degree) <= n) low = mid;
    else high = mid;
  }
  return low;
}

function firstPrimes(count) {
  const out = [];
  for (let n = 2; out.length < count; n++) {
    let prime = true;
    for (let d = 2; d * d <= n; d++) {
      if (n % d === 0) {
        prime = false;
        break;
      }
    }
    if (prime) out.push(n);
  }
  return out;
}

// floor(cuberoot(p) * 2^64) is cuberoot(p * 2^192). Subtract the integer part to retain the
// first 64 fractional bits required by FIPS 180-4 section 4.2.3.
const SCALE = 1n << 64n;
const K = firstPrimes(80).map((p) => {
  const scaled = integerRoot(BigInt(p) << 192n, 3);
  return scaled - integerRoot(BigInt(p), 3) * SCALE;
});
if (K[0] !== 0x428a2f98d728ae22n || K[79] !== 0x6c44198c4a475817n)
  throw new Error('SHA-512 constant derivation failed');

const hex = (n) => `0x${n.toString(16).padStart(8, '0')}`;
function array(name, high) {
  const words = K.map((n) => (high ? n >> 32n : n & MASK32));
  const lines = [];
  for (let i = 0; i < words.length; i += 8)
    lines.push(
      '  ' +
        words
          .slice(i, i + 8)
          .map(hex)
          .join(', ') +
        ','
    );
  return `const ${name} = /* @__PURE__ */ Uint32Array.from([\n${lines.join('\n')}\n]);`;
}

const generated = `// BEGIN generated SHA-512 constants
// Generated by test/misc/sha2-constants.js from the FIPS 180-4 cube-root definition.
// prettier-ignore
${array('SHA512_Kh', true)}
// prettier-ignore
${array('SHA512_Kl', false)}
// END generated SHA-512 constants`;

if (process.argv[2] === '--check') {
  const source = readFileSync(new URL('../../src/sha2.ts', import.meta.url), 'utf8');
  const begin = source.indexOf('// BEGIN generated SHA-512 constants');
  const endMarker = '// END generated SHA-512 constants';
  const end = source.indexOf(endMarker, begin) + endMarker.length;
  if (begin < 0 || end < endMarker.length || source.slice(begin, end) !== generated)
    throw new Error('src/sha2.ts SHA-512 constants are out of date');
} else {
  console.log(generated);
}

// SHA2-512 is slower than sha256 in js because u64 operations are slow.

// SHA-384 / SHA-512 round constants (FIPS 180-4 §4.2.3): the first 64 fractional bits of the cube
// roots of the first 80 primes, as interleaved u32 halves (`K[2 * t]` high, `K[2 * t + 1]` low).
// Derived at import instead of shipping the 160-word table: ~0.2 ms once, ~0.9 KB less gzip.
// `test/misc/sha2-constants.js --check` compares this block against the FIPS table.
// BEGIN derived SHA-512 constants
const SHA512_K = /* @__PURE__ */ (() => {
  const K = new Uint32Array(160);
  const big = BigInt;
  const _2n = big(2);
  const _3n = big(3);
  const _2_32n = big(2 ** 32);
  for (let p = 2, i = 0; i < 160; p++) {
    // Trial division: `d` stops at the smallest divisor > 1, which is `p` itself for primes.
    let d = 2;
    while (p % d) d++;
    if (d < p) continue;
    // floor(cbrt(p) * 2**64) is the integer cube root of n = p * 2**192. Integer Newton iteration:
    // from any x > 0 one step lands at or above the root, then steps decrease strictly until the
    // root is reached. The float estimate only saves iterations; exactness does not depend on it.
    const n = big(p) << big(192);
    let y = big(Math.ceil(Math.cbrt(p) * 2 ** 40)) << big(24);
    let x;
    do {
      x = y;
      y = (_2n * x + n / (x * x)) / _3n;
    } while (y < x);
    // The Uint32Array store wraps mod 2**32, dropping the root's integer part (bits 64 and up).
    K[i++] = Number(x / _2_32n);
    K[i++] = Number(x % _2_32n);
  }
  return K;
})();
// END derived SHA-512 constants


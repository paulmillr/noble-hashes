// Standalone two-round ring compressor, generated from the same template as SHA2_32B.process(),
// used only by the short one-shot path. S is the chaining value (updated in place); W is the loaded block and is
// clobbered. S is an Int32Array: JSC deoptimizes Uint32Array loads which have bit 31 set.
// This stays outside the lease's try/finally: wrapping the hot loop in a finally region prevents
// V8 from optimizing it.
// BEGIN generated SHA-256 compression
// Generated by test/misc/unrolled-sha2.js from FIPS 180-4. Do not edit by hand.
// prettier-ignore
function sha256Compress(S: TArg<Int32Array>, W: TArg<Uint32Array>): void {
  let A = S[0], B = S[1], C = S[2], D = S[3], E = S[4], F = S[5], G = S[6], H = S[7];
  let T1 = 0, T2 = 0;
  for (let i = 0; i < 64; i += 2) {
    const j = i & 15;
    if (i >= 16) {
      const W15 = W[(j + 1) & 15], W2 = W[(j + 14) & 15];
      W[j] = ((rotr(W2, 17) ^ rotr(W2, 19) ^ (W2 >>> 10)) + W[(j + 9) & 15] + (rotr(W15, 7) ^ rotr(W15, 18) ^ (W15 >>> 3)) + W[j]) | 0;
    }
    T1 = (H + (rotr(E, 6) ^ rotr(E, 11) ^ rotr(E, 25)) + (G ^ (E & (F ^ G))) + SHA256_K[i] + W[j]) | 0;
    T2 = ((rotr(A, 2) ^ rotr(A, 13) ^ rotr(A, 22)) + ((A & B) ^ (C & (A ^ B)))) | 0;
    H = G; G = F; F = E; E = (D + T1) | 0; D = C; C = B; B = A; A = (T1 + T2) | 0;
    const j1 = (i + 1) & 15;
    if (i >= 16) {
      const W15 = W[(j1 + 1) & 15], W2 = W[(j1 + 14) & 15];
      W[j1] = ((rotr(W2, 17) ^ rotr(W2, 19) ^ (W2 >>> 10)) + W[(j1 + 9) & 15] + (rotr(W15, 7) ^ rotr(W15, 18) ^ (W15 >>> 3)) + W[j1]) | 0;
    }
    T1 = (H + (rotr(E, 6) ^ rotr(E, 11) ^ rotr(E, 25)) + (G ^ (E & (F ^ G))) + SHA256_K[i + 1] + W[j1]) | 0;
    T2 = ((rotr(A, 2) ^ rotr(A, 13) ^ rotr(A, 22)) + ((A & B) ^ (C & (A ^ B)))) | 0;
    H = G; G = F; F = E; E = (D + T1) | 0; D = C; C = B; B = A; A = (T1 + T2) | 0;
  }
  S[0] = (A + S[0]) | 0; S[1] = (B + S[1]) | 0; S[2] = (C + S[2]) | 0; S[3] = (D + S[3]) | 0;
  S[4] = (E + S[4]) | 0; S[5] = (F + S[5]) | 0; S[6] = (G + S[6]) | 0; S[7] = (H + S[7]) | 0;
}
// END generated SHA-256 compression

// Messages of 0..55 bytes pad to one block and 56..119 bytes to exactly two. Both geometries go
// through one loop and one compressor: separately spelled-out one- and two-block cores would
// each carry another textual copy of the round function into every sha256 bundle.
// The caller owns and wipes W and S.
function sha256OneShotCore(
  input: TArg<Uint8Array>,
  len: number,
  is224: boolean,
  W: TArg<Uint32Array>,
  S: TArg<Int32Array>
): TRet<Uint8Array> {
  // The exported IV tables are mutable for backwards compatibility; read them on every call.
  S.set(is224 ? SHA224_IV : SHA256_IV);
  for (let start = 0; ; start += 64) {
    W.fill(0);
    // Message bytes inside this block: 0 when the second block holds only padding.
    const blockLen = Math.min(64, Math.max(0, len - start));
    let pos = 0;
    for (; pos + 4 <= blockLen; pos += 4) {
      const offset = start + pos;
      W[pos >>> 2] =
        (input[offset] << 24) |
        (input[offset + 1] << 16) |
        (input[offset + 2] << 8) |
        input[offset + 3];
    }
    let word = 0;
    let shift = 24;
    for (; pos < blockLen; pos++, shift -= 8) word |= input[start + pos] << shift;
    // The 0x80 terminator follows the last message byte: it lands in the block where the message
    // ends, which is the second one only if the message fills the first block completely.
    if (len >= start && blockLen < 64) W[pos >>> 2] = word | (0x80 << shift);
    // The 64-bit length needs 8 bytes after the terminator; len <= 119 keeps the high word zero.
    const last = len - start < 56;
    if (last) W[15] = len * 8;
    sha256Compress(S, W);
    if (last) break;
  }
  const out = new Uint8Array(is224 ? 28 : 32);
  for (let pos = 0; pos < out.length; pos += 4) setBig32(out, pos, S[pos >>> 2]);
  return out as TRet<Uint8Array>;
}

function sha256HashOneShot(input: TArg<Uint8Array>, len: number, is224: boolean): TRet<Uint8Array> {
  const shared = !sha256OneShotBusy;
  const W = shared ? SHA256_W : new Uint32Array(16);
  const S = shared ? SHA256_S : new Int32Array(8);
  if (shared) sha256OneShotBusy = true;
  try {
    return sha256OneShotCore(input, len, is224, W, S);
  } finally {
    clean(W, S);
    if (shared) sha256OneShotBusy = false;
  }
}

function sha256Wrap<T extends Hash<T>>(
  stateful: TArg<TRet<CHash<T>>>,
  is224: boolean
): TRet<CHash<T>> {
  return _wrapShortHash(stateful, 119, (input: TArg<Uint8Array>, len: number) =>
    sha256HashOneShot(input, len, is224)
  );
}


// Default-options one-shot for inputs of at most one 1 KiB chunk. Such inputs have no tree: the
// chunk's last block is the root, so class construction, option copies, and cleanup (which
// dominate tiny hashes) can be skipped. Longer inputs and any options use the stateful class.
// Scratch layout, in 32-bit words: [0, 8) chaining value; [8, 24) message block. It holds only
// public IV words and message-derived state, and is wiped before a call returns or throws.
const B3_CHUNK_SCRATCH = /* @__PURE__ */ new Uint32Array(24);
// Int32 alias used by everything except the compressor. JSC speculates Uint32Array loads as
// int32, and words >= 2^31 can trap the one-shot glue in repeated deoptimization; Int32Array
// loads never overflow. The compressor keeps seeing only Uint32Array, so it stays monomorphic.
const B3_CHUNK_WORDS = /* @__PURE__ */ new Int32Array(B3_CHUNK_SCRATCH.buffer);
// Inputs are plain Uint8Arrays (checked by _wrapShortHash), so no input-controlled code can run
// while the scratch is live. The lease is defense in depth: a reentrant call would get private
// scratch instead of aliasing the active call.
let b3ChunkBusy = false;

// Decode `blockLen` little-endian input bytes into the zero-padded message block w[8, 24).
function b3LoadBlock(
  input: TArg<Uint8Array>,
  inputOffset: number,
  blockLen: number,
  w: TArg<Int32Array>
) {
  let pos = 0;
  let i = 8;
  for (; pos + 4 <= blockLen; pos += 4, i++) {
    const o = inputOffset + pos;
    w[i] = input[o] | (input[o + 1] << 8) | (input[o + 2] << 16) | (input[o + 3] << 24);
  }
  if (pos < blockLen) {
    let word = 0;
    for (let shift = 0; pos < blockLen; pos++, shift += 8)
      word |= input[inputOffset + pos] << shift;
    w[i++] = word;
  }
  for (; i < 24; i++) w[i] = 0;
}

function b3HashChunk(input: TArg<Uint8Array>, len: number): TRet<Uint8Array> {
  const shared = !b3ChunkBusy;
  const s = shared ? B3_CHUNK_SCRATCH : new Uint32Array(24);
  const w = shared ? B3_CHUNK_WORDS : new Int32Array(s.buffer);
  if (shared) b3ChunkBusy = true;
  try {
    w[0] = 0x6a09e667;
    w[1] = 0xbb67ae85;
    w[2] = 0x3c6ef372;
    w[3] = 0xa54ff53a;
    w[4] = 0x510e527f;
    w[5] = 0x9b05688c;
    w[6] = 0x1f83d9ab;
    w[7] = 0x5be0cd19;
    let offset = 0;
    let flags: number = B3_Flags.CHUNK_START;
    // Aligned little-endian input: full non-final blocks are read in place through a word view.
    // The final block is always decoded into owned scratch, so the compressor never reads past a
    // short view (SpiderMonkey handles out-of-bounds zero-padding reads badly).
    const input32 =
      isLE && len > 64 && !(input.byteOffset & 3)
        ? new Uint32Array(input.buffer, input.byteOffset, len >>> 2)
        : undefined;
    // The chunk counter is 0: this is the only chunk.
    for (; len - offset > 64; offset += 64, flags = 0) {
      if (input32) b3Compress(input32, offset >>> 2, s, 0, 0, 64, flags);
      else {
        b3LoadBlock(input, offset, 64, w);
        b3Compress(s, 8, s, 0, 0, 64, flags);
      }
    }
    const blockLen = len - offset;
    b3LoadBlock(input, offset, blockLen, w);
    b3Compress(s, 8, s, 0, 0, blockLen, flags | B3_Flags.CHUNK_END | B3_Flags.ROOT);
    const out = new Uint8Array(32);
    for (let i = 0; i < 8; i++) {
      const word = w[i];
      const pos = i * 4;
      out[pos] = word;
      out[pos + 1] = word >>> 8;
      out[pos + 2] = word >>> 16;
      out[pos + 3] = word >>> 24;
    }
    return out as TRet<Uint8Array>;
  } finally {
    // A plain loop beats fill() for a range this short.
    for (let i = 0; i < 24; i++) w[i] = 0;
    if (shared) b3ChunkBusy = false;
  }
}

/**
 * Ensure to use EITHER `key` OR `context`, not both.
 *
 * * `key`: 32-byte MAC key.
 * * `context`: caller-encoded KDF context bytes. If your protocol defines a
 *   string context, encode it before passing it here.
 *   A good default format for the original context string is
 *   "[application] [commit timestamp] [purpose]".
 */
export type Blake3Opts = {
  /** Desired digest length in bytes. The BLAKE3 spec allows 0..2^64-1 bytes of output. */
  dkLen?: number;
  /** Optional 32-byte MAC key. */
  key?: Uint8Array;
  /** Optional KDF context bytes. */
  context?: Uint8Array;
};

/** Blake3 hash. Can be used as MAC and KDF with caller-encoded context bytes. */
export class _BLAKE3 extends _BLAKE2<_BLAKE3> implements HashXOF<_BLAKE3> {
  readonly canXOF = true;
  private chunkPos = 0; // Position of current block in chunk
  // How many chunks we already have; exact while this stays within
  // JS's safe-integer range.
  private chunksDone = 0;
  private flags = 0 | 0;
  private IV: Uint32Array;
  private state: Uint32Array;
  private stack: Uint32Array[] = [];
  // Output
  private posOut = 0;
  private bufferOut32 = new Uint32Array(16);
  private bufferOut: Uint8Array;
  // Index of output chunk; exact while this stays within JS's
  // safe-integer range.
  private chunkOut = 0;
  private enableXOF = true;

  constructor(opts: Blake3Opts = {}, flags = 0) {
    opts = checkOpts({}, opts);
    super(64, opts.dkLen === undefined ? 32 : opts.dkLen);
    const { key, context } = opts;
    const hasContext = context !== undefined;
    if (key !== undefined) {
      if (hasContext) throw new Error('cannot use both "key" and "context"');
      abytes(key, 32, 'key');
      const k = copyBytes(key);
      this.IV = u32(k);
      swap32IfBE(this.IV);
      this.flags = flags | B3_Flags.KEYED_HASH;
    } else if (hasContext) {
      abytes(context, undefined, 'context');
      const ctx = context;
      const contextKey = new _BLAKE3({ dkLen: 32 }, B3_Flags.DERIVE_KEY_CONTEXT)
        .update(ctx)
        .digest();
      this.IV = u32(contextKey);
      swap32IfBE(this.IV);
      this.flags = flags | B3_Flags.DERIVE_KEY_MATERIAL;
    } else {
      this.IV = B3_IV; // Share the module-private immutable default IV.
      this.flags = flags;
    }
    this.state = this.IV.slice();
    this.bufferOut = u8(this.bufferOut32);
  }
  // _BLAKE2's scalar-state hooks are unused here: BLAKE3 keeps its tree/XOF state in arrays and
  // copies it directly in _cloneInto().
  protected get(): [] {
    return [];
  }
  protected set(): void {}
  protected compress(buf: Uint32Array, bufPos: number = 0, isLast: boolean = false): void {
    // Compress last block
    let flags = this.flags;
    if (!this.chunkPos) flags |= B3_Flags.CHUNK_START;
    if (this.chunkPos === 15 || isLast) flags |= B3_Flags.CHUNK_END;
    if (!isLast) this.pos = this.blockLen;
    // Truncated chunk compression: seed v8..v15 as IV[0..3], t0, t1, block length, and flags,
    // then keep only the first 8 output words.
    const counter = this.chunksDone;
    b3Compress(buf, bufPos, this.state, fromNumL(counter), fromNumH(counter), this.pos, flags);
    this.chunkPos += 1;
    // If current block is last in chunk (16 blocks), then compress chunks
    if (this.chunkPos === 16 || isLast) {
      const { IV, stack, buffer32 } = this;
      // The finished chunk CV is folded in place: each parent copies its two children into
      // buffer32, resets this array to the key words, and compresses into it.
      const chunk = this.state;
      let spare: Uint32Array | undefined;
      // If not the last one, compress only when there are trailing zeros in chunk counter
      // Chunks are used as a binary tree where the current stack is the path.
      // Zero means the current leaf is finished and can be compressed.
      // 1 (001) - leaf not finished (just push current chunk to stack)
      // 2 (010) - leaf finished at depth=1 (merge with last elm on stack and push back)
      // 3 (011) - last leaf not finished
      // 4 (100) - leafs finished at depth=1 and depth=2
      // Reading the low bit is safe for parity, but keep division full-width: shifting would
      // truncate the safe-integer chunk counter to 32 bits.
      for (
        let chunks = this.chunksDone + 1;
        isLast || !(chunks & 1);
        chunks = Math.floor(chunks / 2)
      ) {
        const left = stack.pop();
        if (!left) break;
        buffer32.set(left, 0);
        buffer32.set(chunk, 8);
        chunk.set(IV);
        b3Compress(buffer32, 0, chunk, 0, 0, 64, this.flags | B3_Flags.PARENT);
        // Recycle one popped entry as the next chunk state; wipe any others before dropping.
        if (spare) clean(spare);
        spare = left;
      }
      this.chunksDone++;
      this.chunkPos = 0;
      stack.push(chunk);
      // finish() relies on a fresh key-word state after the last fold (it reruns that parent).
      const next = spare || new Uint32Array(8);
      next.set(IV);
      this.state = next;
    }
    this.pos = 0;
  }
  // Overriding hides _BLAKE2's flat implementation, which would otherwise be inherited
  // and silently miss the tree state (CV stack, chunk counters; get()/set() are stubs here).
  _cloneInto(to?: _BLAKE3): _BLAKE3 {
    const staleOutput = !!to && to.finished && !to.destroyed; // Save before super copies lifecycle.
    to = super._cloneInto(to) as _BLAKE3;
    const { IV, flags, state, chunkPos, posOut, chunkOut, stack, chunksDone } = this;
    to.state.set(state);
    // Clone each CV stack entry by value so extending or destroying the clone
    // cannot alias the source tree state.
    to.stack = stack.map((i) => Uint32Array.from(i));
    if (IV === B3_IV) {
      if (to.IV !== B3_IV) clean(to.IV);
      to.IV = B3_IV; // Share immutable default; configured IVs stay private.
    } else if (to.IV === B3_IV) {
      to.IV = IV.slice();
    } else {
      to.IV.set(IV);
    }
    to.flags = flags;
    to.chunkPos = chunkPos;
    to.chunksDone = chunksDone;
    to.posOut = posOut;
    to.chunkOut = chunkOut;
    to.enableXOF = this.enableXOF;
    if (this.finished) {
      to.bufferOut32.set(this.bufferOut32);
    } else if (staleOutput) {
      clean(to.bufferOut32); // Wipe stale output; finish() overwrites scratch.
    }
    return to;
  }
  destroy(): void {
    this.destroyed = true;
    clean(this.state, this.buffer32, this.bufferOut32);
    if (this.IV !== B3_IV) clean(this.IV);
    clean(...this.stack);
  }
  // Root/XOF compression: rerun the same ROOT inputs with incrementing output
  // counter `t` and materialize all 16 output words.
  // Same as b2Compress, but doesn't modify state and returns 16 u32 array (instead of 8)
  private b2CompressOut() {
    const { state: s, pos, flags, buffer32, bufferOut32: out32 } = this;
    const outCounter = this.chunkOut++;
    const t0 = fromNumL(outCounter);
    const t1 = fromNumH(outCounter);
    swap32IfBE(buffer32);
    b3Compress(buffer32, 0, s, t0, t1, pos, flags, out32);
    swap32IfBE(buffer32);
    swap32IfBE(out32);
    this.posOut = 0;
  }
  protected finish(): void {
    if (this.finished) return;
    this.finished = true;
    // Padding
    this.buffer.fill(0, this.pos);
    // Process last chunk
    let flags = this.flags | B3_Flags.ROOT;
    if (this.stack.length) {
      // Finalize the current chunk first, then rerun the last parent
      // compression as ROOT with t = 0 and b = 64.
      flags |= B3_Flags.PARENT;
      swap32IfBE(this.buffer32);
      this.compress(this.buffer32, 0, true);
      swap32IfBE(this.buffer32);
      this.chunksDone = 0;
      this.pos = this.blockLen;
    } else {
      flags |= (!this.chunkPos ? B3_Flags.CHUNK_START : 0) | B3_Flags.CHUNK_END;
    }
    this.flags = flags;
    this.b2CompressOut();
  }
  private writeInto(out: TArg<Uint8Array>): TRet<Uint8Array> {
    aexists(this, false);
    abytes(out);
    this.finish();
    const { blockLen, bufferOut } = this;
    for (let pos = 0, len = out.length; pos < len;) {
      if (this.posOut >= blockLen) this.b2CompressOut();
      const take = Math.min(blockLen - this.posOut, len - pos);
      out.set(bufferOut.subarray(this.posOut, this.posOut + take), pos);
      this.posOut += take;
      pos += take;
    }
    return out as TRet<Uint8Array>;
  }
  xofInto(out: TArg<Uint8Array>): TRet<Uint8Array> {
    if (!this.enableXOF) throw new Error('no XOF after digest()');
    return this.writeInto(out);
  }
  xof(bytes: number): TRet<Uint8Array> {
    anumber(bytes);
    return this.xofInto(new Uint8Array(bytes));
  }
  digestInto(out: TArg<Uint8Array>): void {
    aoutput(out, this);
    if (this.finished) throw new Error('digest() was already called');
    this.enableXOF = false;
    // `aoutput(...)` allows oversized buffers; digestInto() must fill only the configured digest.
    this.writeInto(out.length === this.outputLen ? out : out.subarray(0, this.outputLen));
    this.destroy();
  }
  digest(): TRet<Uint8Array> {
    const out = new Uint8Array(this.outputLen);
    this.digestInto(out);
    return out as TRet<Uint8Array>;
  }
}

